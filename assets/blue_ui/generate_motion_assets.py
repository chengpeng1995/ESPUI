#!/usr/bin/env python3
"""Bake native carousel size steps from approved icon PNGs, without runtime transforms."""
from pathlib import Path
from PIL import Image
from generate_assets import encode565, APPS
OUT=Path(__file__).resolve().parent
sizes=(88,100,106,112,118)
header=['#pragma once','#include "lvgl.h"','#ifdef __cplusplus','extern "C" {','#endif']
source=['/* Generated by generate_motion_assets.py; native carousel size steps. */','#include "blue_ui_motion_assets.h"']
total=0
for app in APPS:
    original=Image.open(OUT/f'{app}.png').convert('RGBA')
    for size in sizes:
        name=f'blue_icon_{app}_{size}'
        im=original.resize((size,size),Image.Resampling.LANCZOS)
        data,_=encode565(im,True);total+=len(data)
        source.append(f'const __attribute__((aligned(128))) uint8_t {name}_pixels[{len(data)}] = {{')
        for pos in range(0,len(data),24):source.append('    '+','.join(f'0x{byte:02x}' for byte in data[pos:pos+24])+',')
        source.extend(['};',f'''const lv_image_dsc_t {name} = {{
 .header = {{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_RGB565A8,.flags=0,.w={size},.h={size},.stride={size*2}}},
 .data_size=sizeof({name}_pixels),.data={name}_pixels,
}};'''])
        header.append(f'LV_IMAGE_DECLARE({name});')
header+=['#ifdef __cplusplus','}','#endif']
(OUT/'blue_ui_motion_assets.h').write_text('\n'.join(header)+'\n')
(OUT/'blue_ui_motion_assets.c').write_text('\n'.join(source)+'\n')
print(f'30 native carousel frames, {total} raw bytes')
